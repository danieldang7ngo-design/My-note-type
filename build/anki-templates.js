'use strict';
/* Build the three files an Anki note type can actually hold — Front template,
   Back template, Styling — with the media JS inlined into the templates.

   Why: AnkiWeb and AnkiMobile insert the card HTML instead of parsing it as a
   document, so <script src> tags that arrive inside a template never execute
   (see docs/BUG_LOG.md BUG-056). Inline <script> bodies do run, so inlining
   removes the whole class of failure: no media sync, no stale cache, no
   relative-path resolution, no loader.

   Source of truth stays the root modules + stylesheet; `dist/` is generated.
     node build/anki-templates.js
*/
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, s) => {
  const out = path.join(ROOT, p);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, s);
};

const TARGETS = [
  {
    name: 'typing',
    outDir: 'dist',
    media: '',
    front: 'Front.html',
    back: 'Back.html',
    css: '_hna_styles_v7.css',
    modules: ['_hna_storage.js', '_hna_engine.js', '_hna_diff.js', '_hna_typing.js', '_hna_aurora.js'],
    inits: {} // modules self-init per card
  },
  {
    name: 'mcq',
    outDir: 'dist/mcq',
    media: 'mcq/',
    front: 'mcq/Front.html',
    back: 'mcq/Back.html',
    css: 'mcq/_mcq_styles.css',
    modules: ['_mcq_storage.js', '_mcq_engine.js', '_mcq_logic.js', '_mcq_aurora.js'],
    inits: { front: 'AnkiMCQ.initFront()', back: 'AnkiMCQ.initBack()' }
  },
  {
    name: 'tf',
    outDir: 'dist/tf',
    media: 'tf/',
    front: 'tf/Front.html',
    back: 'tf/Back.html',
    css: 'tf/_tf_styles.css',
    modules: ['_tf_storage.js', '_tf_engine.js', '_tf_logic.js', '_tf_aurora.js'],
    inits: { front: 'AnkiTF.initFront()', back: 'AnkiTF.initBack()' }
  }
];

/* Anki substitutes every {{token}} in the template text — including inside a
   <script> block. One unlucky field name would inject note content straight
   into the JS. Refuse to build rather than ship that. */
function assertInlinable(name, src) {
  if (src.indexOf('{{') !== -1) {
    throw new Error(name + ': contains "{{" — Anki would substitute it inside the script');
  }
  if (src.indexOf('</script') !== -1) {
    throw new Error(name + ': contains "</script" — it would close the inline block early');
  }
}

/* The inline bootstrap (BUG-056) exists only to load external files. With the
   modules inlined it is dead weight: remove it, keeping any init call the
   template made inside it. */
function stripBootstrap(html, inits) {
  return html.replace(/<script>((?:(?!<\/script>)[\s\S])*?)<\/script>/g, (block, body) => {
    if (body.indexOf('__hnaScriptMode') === -1 && body.indexOf('__mcqScriptMode') === -1 && body.indexOf('__tfScriptMode') === -1) return block;
    return '';
  });
}

function inlineModules(html, modules, label, media) {
  let out = html;
  modules.forEach((name) => {
    const tag = '<script src="' + name + '"></script>';
    if (out.indexOf(tag) === -1) throw new Error(label + ': script tag for ' + name + ' not found');
    const src = read(media + name).replace(/\r\n/g, '\n').trim();
    assertInlinable(name, src);
    out = out.replace(tag, '<script>\n/* ---- ' + name + ' (inlined: AnkiWeb never runs <script src> in a card) ---- */\n' + src + '\n</script>');
  });
  return out;
}

function stripStylesheetLink(html) {
  return html.replace(/<link\b[^>]*href="[^"]*"[^>]*>\s*\n?/gi, '');
}

function build(target) {
  const banner = (which) =>
    '<!-- ' + target.name + ' note type — ' + which + ' template.\n' +
    '     Generated by build/anki-templates.js — do not edit dist/ by hand.\n' +
    '     Paste as-is into Anki > Cards… > ' + which.slice(0, 4) + '. The styling lives in the\n' +
    '     Styling field (dist/' + (target.name === 'typing' ? '' : target.name + '/') + 'styling.css); only the\n' +
    '     font files stay in collection.media. -->\n';

  ['front', 'back'].forEach((face) => {
    let html = read(target[face]);
    html = stripStylesheetLink(html);
    html = stripBootstrap(html, target.inits);
    html = inlineModules(html, target.modules, target[face], target.media);
    if (target.inits[face]) {
      html = html.trimEnd() + '\n<script>\n// modules above are inlined; init runs once per card, as a card load should.\n' +
        target.inits[face] + ';\n</script>\n';
    }
    const out = banner(face === 'front' ? 'Front' : 'Back') + html;
    // NOTE: the template keeps its own {{field}} placeholders — that is the
    // point of a template. Only the inlined module bodies must be brace-free
    // (asserted per module above), so no output-wide brace check here.
    const file = target.outDir + '/' + (face === 'front' ? 'Front.html' : 'Back.html');
    write(file, out);
    console.log('  ' + file + '  ' + (out.length / 1024).toFixed(1) + ' KB');
  });

  const css = read(target.css);
  assertInlinable(target.css, css);
  const cssOut = '/* ' + target.name + ' note type — Styling field content.\n' +
    '   Generated by build/anki-templates.js — edit ' + target.css + ' instead. */\n' + css;
  write(target.outDir + '/styling.css', cssOut);
  console.log('  ' + target.outDir + '/styling.css  ' + (cssOut.length / 1024).toFixed(1) + ' KB');
}

console.log('building paste-ready note type files…');
TARGETS.forEach((t) => {
  console.log(t.name + ':');
  build(t);
});
console.log('done.');
